"""Wrap the plain Prometheus rules (single source of truth) into a PrometheusRule custom resource.

    python scripts/render_prometheus_rule.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "infra" / "monitoring" / "prometheus" / "rules" / "riskpulse-alerts.yml"
DST = ROOT / "infra" / "monitoring" / "k8s" / "prometheusrule.yaml"


def main() -> None:
    body = SRC.read_text(encoding="utf-8").splitlines()
    start = next(i for i, line in enumerate(body) if line.startswith("groups:"))
    groups = "\n".join("  " + line if line else line for line in body[start:])
    header = (
        "# GENERATED by scripts/render_prometheus_rule.py from prometheus/rules/riskpulse-alerts.yml — do not edit.\n"
        "apiVersion: monitoring.coreos.com/v1\nkind: PrometheusRule\nmetadata:\n  name: riskpulse-alerts\n"
        "  namespace: monitoring\n  labels:\n    app.kubernetes.io/part-of: riskpulse\nspec:\n"
    )
    DST.write_text(header + groups + "\n", encoding="utf-8")
    print(f"wrote {DST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
