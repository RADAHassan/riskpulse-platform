"""Render infra/k8s/security/networkpolicies.yaml: default-deny + one allow-list policy per workload.

    python scripts/gen_k8s_security.py

Only the flows listed in EDGES are allowed (plus DNS and Prometheus scraping). Anything else is dropped.
"""

from __future__ import annotations

from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "infra" / "k8s" / "security" / "networkpolicies.yaml"
NS = "riskpulse"

PORTS = {"api-gateway": 8080, "auth-service": 8081, "customer-service": 8082, "transaction-service": 8083,
         "risk-service": 8084, "notification-service": 8085, "audit-service": 8086, "ml-serving": 8000,
         "frontend": 8080, "mlflow": 5000, "postgres": 5432, "postgres-exporter": 9187}
SPRING = ["api-gateway", "auth-service", "customer-service", "transaction-service", "risk-service",
          "notification-service", "audit-service"]
DBS = {"auth-service", "customer-service", "transaction-service", "risk-service", "notification-service",
       "audit-service", "mlflow", "postgres-exporter"}

# (source, destination)
EDGES = [
    ("frontend", "api-gateway"),
    ("api-gateway", "auth-service"), ("api-gateway", "customer-service"), ("api-gateway", "transaction-service"),
    ("api-gateway", "risk-service"), ("api-gateway", "notification-service"), ("api-gateway", "audit-service"),
    ("api-gateway", "ml-serving"),
    ("transaction-service", "risk-service"), ("transaction-service", "audit-service"),
    ("risk-service", "ml-serving"), ("risk-service", "audit-service"), ("risk-service", "notification-service"),
    ("risk-service", "transaction-service"),
    ("auth-service", "audit-service"), ("customer-service", "audit-service"),
    ("ml-serving", "mlflow"),
    ("mlops-pipeline", "mlflow"), ("mlops-pipeline", "ml-serving"),
] + [(s, "auth-service") for s in SPRING if s != "auth-service"] + [(s, "postgres") for s in DBS]
# every Spring service validates JWTs against the auth-service JWKS (egress to auth-service:8081)

WORKLOADS = [*SPRING, "ml-serving", "frontend", "mlflow", "postgres", "postgres-exporter", "mlops-pipeline"]


def selector(name: str) -> str:
    return f"podSelector: {{ matchLabels: {{ app.kubernetes.io/name: {name} }} }}"


def policy(name: str) -> str:
    port = PORTS.get(name)
    ingress, egress = [], []
    for src, dst in EDGES:
        if dst == name and src != name:
            ingress.append(f"""    - from:
        - {selector(src)}
      ports:
        - {{ protocol: TCP, port: {PORTS[name]} }}""")
        if src == name:
            egress.append(f"""    - to:
        - {selector(dst)}
      ports:
        - {{ protocol: TCP, port: {PORTS[dst]} }}""")
    if name == "frontend":
        ingress.append("""    - from:
        - namespaceSelector: { matchLabels: { kubernetes.io/metadata.name: ingress-nginx } }
      ports:
        - { protocol: TCP, port: 8080 }""")
    if port and name != "mlops-pipeline":
        # Prometheus (namespace monitoring) scrapes /actuator/prometheus and /metrics
        ingress.append(f"""    - from:
        - namespaceSelector: {{ matchLabels: {{ kubernetes.io/metadata.name: monitoring }} }}
      ports:
        - {{ protocol: TCP, port: {port} }}""")
    # DNS (CoreDNS in kube-system)
    egress.append("""    - to:
        - namespaceSelector: { matchLabels: { kubernetes.io/metadata.name: kube-system } }
          podSelector: { matchLabels: { k8s-app: kube-dns } }
      ports:
        - { protocol: UDP, port: 53 }
        - { protocol: TCP, port: 53 }""")
    if name in ("ml-serving", "mlops-pipeline"):
        pass  # MLflow artifacts are served through the MLflow proxy: no direct internet egress needed
    ing = "\n".join(ingress) if ingress else "    []"
    return f"""---
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
metadata:
  name: {name}
  namespace: {NS}
spec:
  {selector(name)}
  policyTypes: [Ingress, Egress]
  ingress:
{ing}
  egress:
{chr(10).join(egress)}
"""


def main() -> None:
    header = f"""# GENERATED by scripts/gen_k8s_security.py — do not edit by hand.
# Zero trust inside the namespace: default deny (ingress + egress), then one explicit allow-list per workload.
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
metadata:
  name: default-deny-all
  namespace: {NS}
spec:
  podSelector: {{}}
  policyTypes: [Ingress, Egress]
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(header + "".join(policy(w) for w in WORKLOADS), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
